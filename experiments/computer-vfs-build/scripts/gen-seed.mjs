// Generates src/seed-app.ts from seed/app/ so the DO can write the scaffold into the VFS
// the way Galaxy would (ws.fs.writeFile per file), rather than shelling out to `cp` inside
// the container. Run once with `npm run seed:gen`; the OUTPUT IS COMMITTED. This is a
// one-shot generator, not a build step — nothing in the dev loop runs it (no-build-in-dev).
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "seed", "app");

/** @type {string[]} */
const files = [];
(function walk(dir) {
  for (const entry of readdirSync(dir).sort()) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full);
    else files.push(full);
  }
})(root);

const entries = files.map((full) => {
  const rel = relative(root, full).split("\\").join("/");
  return `  ${JSON.stringify(rel)}: ${JSON.stringify(readFileSync(full, "utf8"))},`;
});

const out = `// GENERATED by scripts/gen-seed.mjs from seed/app/ — do not hand-edit.
// The real apps/nebula/container/app scaffold, inlined so the DO can write it into the VFS
// with ws.fs.writeFile (arm A), matching how Galaxy would deliver codegen output. Arm B
// reads the identical bytes from /seed/app, baked into the image by the Dockerfile.
export const SEED_APP: Record<string, string> = {
${entries.join("\n")}
};

export const SEED_FILE_COUNT = ${files.length};
export const SEED_BYTES = ${files.reduce((n, f) => n + statSync(f).size, 0)};
`;

mkdirSync(join(here, "..", "src"), { recursive: true });
writeFileSync(join(here, "..", "src", "seed-app.ts"), out);
console.log(`wrote src/seed-app.ts — ${files.length} files`);
