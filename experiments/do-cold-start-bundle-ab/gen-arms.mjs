/**
 * Generate the bundle-size ladder — one Worker per arm.
 *
 * WHY GENERATED. The whole experiment rests on the arms being identical except for ONE import.
 * Hand-writing six near-copies invites a stray difference that silently becomes a second
 * variable. Everything here comes from the single MANIFEST below.
 *
 * WHY REAL IMPORTS, not synthetic weight. An earlier attempt varied generated module weight and
 * was inconclusive: repetitive generated classes gzip to almost nothing and V8 treats
 * homogeneous shapes very differently from heterogeneous library code (see RESULTS.md).
 * These are real packages, giving a real spread of parse + retained-heap cost.
 *
 * USAGE (from this directory):
 *   node gen-arms.mjs            # writes src/arm-*.ts + wrangler.*.jsonc
 */

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));

/** id → the ONE package each arm additionally imports (null = baseline, mesh only). */
export const MANIFEST = [
  { id: 'mesh', pkg: null, note: 'baseline — @lumenize/mesh only' },
  { id: 'git', pkg: 'isomorphic-git', note: 'git implementation' },
  { id: 'shell', pkg: '@cloudflare/shell', note: 'pulls isomorphic-git + @cloudflare/codemode' },
  { id: 'auth', pkg: '@lumenize/nebula-auth', note: 'auth/registry/profile' },
  { id: 'validator', pkg: '@lumenize/ts-runtime-parser-validator', note: 'bundles tsc' },
  { id: 'nebula', pkg: '@lumenize/nebula', note: 'the full barrel — what apps/nebula ships' },
  // Source-identical to the `nebula` arm; the difference is applied at BUNDLE time by
  // `--alias @lumenize/ts-runtime-parser-validator=./src/stub-validator.ts`, which yields a
  // faithful "nebula minus validator" — the shape the worker takes if tsc moves to the
  // container. Lands ~2.6 MB, inside the unsampled 684 KiB → 9.2 MB gap. See package.json.
  {
    id: 'nebula-lite',
    pkg: '@lumenize/nebula',
    note: 'nebula with the validator aliased out',
    // NOTE: the wrangler.jsonc `alias` FIELD works; the `--alias` CLI flag silently did not
    // (it produced a byte-identical bundle). Keep this in config, not on the command line.
    alias: { '@lumenize/ts-runtime-parser-validator': './src/stub-validator.ts' },
  },
];

const entry = ({ id, pkg, note }) => `/* GENERATED by gen-arms.mjs — DO NOT EDIT. arm=${id} (${note}) */
import { env } from 'cloudflare:workers';
import { EchoDO } from './echo-do.js';
${pkg ? `import * as heavy from '${pkg}';` : '// baseline arm — no extra import'}

export { EchoDO };
${
  pkg
    ? `// Referenced so the graph can't be tree-shaken away, which would silently turn this
// arm back into the baseline. Assigning to globalThis is a side effect esbuild keeps.
(globalThis as any).__arm = { id: '${id}', exports: Object.keys(heavy as any).length };`
    : `(globalThis as any).__arm = { id: '${id}' };`
}

export default {
  async fetch(request: Request): Promise<Response> {
    const url = new URL(request.url);
    if (url.pathname === '/echo') {
      // A previously-unused name => a brand-new DO. A repeated name => already exists.
      const name = url.searchParams.get('name') ?? 'default';
      const value = await (env as any).ECHO.getByName(name).echo('x');
      return Response.json({ arm: '${id}', name, value });
    }
    return new Response('Not Found', { status: 404 });
  },
};
`;

const wrangler = ({ id, note, alias }) => `{
  // GENERATED by gen-arms.mjs — DO NOT EDIT. arm=${id} (${note})
  // Identical across every arm except "name", "main", and (where present) "alias", so the
  // ONLY variable is what ends up in the module graph.
  "name": "do-cs-${id}",
  "main": "./src/arm-${id}.ts",
  "compatibility_date": "2026-03-12",
  "compatibility_flags": ["nodejs_compat"],
${alias ? `  "alias": ${JSON.stringify(alias)},\n` : ''}  "durable_objects": {
    "bindings": [{ "name": "ECHO", "class_name": "EchoDO" }]
  },
  "exports": {
    "EchoDO": { "type": "durable-object", "storage": "sqlite" }
  }
}
`;

for (const arm of MANIFEST) {
  writeFileSync(resolve(HERE, `src/arm-${arm.id}.ts`), entry(arm), 'utf8');
  writeFileSync(resolve(HERE, `wrangler.${arm.id}.jsonc`), wrangler(arm), 'utf8');
  console.log(`arm ${arm.id.padEnd(10)} → src/arm-${arm.id}.ts + wrangler.${arm.id}.jsonc  (${arm.note})`);
}
