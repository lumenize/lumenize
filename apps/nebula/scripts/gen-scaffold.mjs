// Generates src/scaffold-seed.ts from container/app/ so the Galaxy can seed the
// framework scaffold into its own Workspace VFS with ws.fs.writeFile — the container's
// /workspace IS that tree via the FUSE mount, so seeding the VFS is the whole delivery
// (no COPY into the image, no push step). Run `node scripts/gen-scaffold.mjs` after
// editing container/app/; the OUTPUT IS COMMITTED. This is a one-shot generator, not a
// build step — nothing in the dev loop runs it (no-build-in-dev); the scaffold-seed
// drift test reds when the committed embed and container/app/ disagree.
// (Pattern productionized from experiments/computer-vfs-build/scripts/gen-seed.mjs.)
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "container", "app");

/** @type {string[]} */
const files = [];
(function walk(dir) {
  for (const entry of readdirSync(dir).sort()) {
    if (entry === "node_modules" || entry === "dist" || entry === "package-lock.json") continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full);
    else files.push(full);
  }
})(root);

const entries = files.map((full) => {
  const rel = relative(root, full).split("\\").join("/");
  return `  ${JSON.stringify(rel)}: ${JSON.stringify(readFileSync(full, "utf8"))},`;
});

const out = `// GENERATED by scripts/gen-scaffold.mjs from container/app/ — do not hand-edit.
// The framework scaffold the Galaxy seeds into its Workspace VFS (path → contents,
// relative to the workspace root). container/app/ is the EDITABLE source of truth;
// re-run the generator after changing it (the drift test in
// test/scaffold-seed-drift.test.ts reds when the two disagree). package.json rides
// along as the workspace's own manifest, but the BAKED dep tree the build resolves is
// the image's (container/Dockerfile installs the same manifest at the image root).
export const SCAFFOLD_FILES: Record<string, string> = {
${entries.join("\n")}
};
`;

const target = join(here, "..", "src", "scaffold-seed.ts");
if (process.argv.includes("--check")) {
  // Drift gate (wired into the package `test` script): exits non-zero when the committed
  // embed differs from what container/app/ would generate NOW.
  const current = readFileSync(target, "utf8");
  if (current !== out) {
    console.error("scaffold-seed DRIFT: container/app/ changed — run `node scripts/gen-scaffold.mjs` and commit src/scaffold-seed.ts");
    process.exit(1);
  }
  console.log("scaffold-seed in sync");
} else {
  writeFileSync(target, out);
  console.log(`wrote src/scaffold-seed.ts — ${files.length} files`);
}
